template <class Op> struct GenericOpPattern : public OpConversionPattern<Op> {
  using OpConversionPattern<Op>::OpConversionPattern;

  LogicalResult
  matchAndRewrite(Op op, typename Op::Adaptor adaptor,
                  ConversionPatternRewriter &rewriter) const override {
    SmallVector<Type> retTypes;
    if (failed(this->getTypeConverter()->convertTypes(op->getResultTypes(),
                                                      retTypes)))
      return failure();
    rewriter.replaceOpWithNewOp<Op>(op, retTypes, adaptor.getOperands(),
                                    op->getAttrs());

    return success();
  }
};

void populateGenericTritonPatterns(RewritePatternSet &patterns,
                                   TypeConverter &typeConverter);
void populateGenericArithPatterns(RewritePatternSet &patterns,
                                  TypeConverter &typeConverter);
void populateGenericPatterns(RewritePatternSet &patterns,
                             TypeConverter &typeConverter);

